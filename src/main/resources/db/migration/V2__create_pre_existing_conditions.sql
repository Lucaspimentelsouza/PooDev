CREATE TABLE pre_existing_conditions (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         condition_name VARCHAR(130) NOT NULL,
                                         active BOOLEAN NOT NULL,
                                         patient_id BIGINT NOT NULL,

                                         CONSTRAINT fk_pre_existing_conditions_patient
                                             FOREIGN KEY (patient_id) REFERENCES patients (id)
);

CREATE INDEX idx_pre_existing_conditions_patient
    ON pre_existing_conditions (patient_id);