CREATE TABLE patients (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          patients_cpf VARCHAR(14),
                          name VARCHAR(70) NOT NULL,
                          fall_risk BOOLEAN NOT NULL,
                          birth_date DATE,
                          gender VARCHAR(255),
                          health_insurance VARCHAR(255),
                          phone VARCHAR(255),

                          CONSTRAINT uk_patients_cpf UNIQUE (patients_cpf)
);

CREATE TABLE doctors (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         username VARCHAR(255) NOT NULL,
                         password VARCHAR(255) NOT NULL,
                         active BOOLEAN NOT NULL,
                         full_name VARCHAR(70) NOT NULL,
                         medical_license VARCHAR(20) NOT NULL,
                         specialty VARCHAR(100),
                         professional_email VARCHAR(150),
                         created_at TIMESTAMP WITHOUT TIME ZONE,
                         updated_at TIMESTAMP WITHOUT TIME ZONE,

                         CONSTRAINT uk_doctors_username UNIQUE (username),
                         CONSTRAINT uk_doctors_medical_license UNIQUE (medical_license)
);

CREATE TABLE consultations (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               consultation_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                               chief_complaint VARCHAR(255),
                               diagnostic_hypothesis VARCHAR(255),
                               clinical_plan TEXT,
                               patient_id BIGINT NOT NULL,
                               doctor_id BIGINT NOT NULL,

                               CONSTRAINT fk_consultations_patient
                                   FOREIGN KEY (patient_id) REFERENCES patients (id),

                               CONSTRAINT fk_consultations_doctor
                                   FOREIGN KEY (doctor_id) REFERENCES doctors (id)
);

CREATE TABLE allergys (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          allergen VARCHAR(130) NOT NULL,
                          active BOOLEAN NOT NULL,
                          patient_id BIGINT NOT NULL,

                          CONSTRAINT fk_allergys_patient
                              FOREIGN KEY (patient_id) REFERENCES patients (id)
);

CREATE TABLE continuous_medications (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        medication_name VARCHAR(130) NOT NULL,
                                        dosage VARCHAR(70),
                                        active BOOLEAN NOT NULL,
                                        patient_id BIGINT NOT NULL,

                                        CONSTRAINT fk_continuous_medications_patient
                                            FOREIGN KEY (patient_id) REFERENCES patients (id)
);

CREATE TABLE surgeries (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           procedure_name VARCHAR(130) NOT NULL,
                           surgery_name DATE NOT NULL,
                           notes TEXT,
                           patient_id BIGINT NOT NULL,

                           CONSTRAINT fk_surgeries_patient
                               FOREIGN KEY (patient_id) REFERENCES patients (id)
);

CREATE TABLE vital_signs (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             blood_pressure VARCHAR(25) NOT NULL,
                             weight NUMERIC(5, 2) NOT NULL,
                             body_temperature NUMERIC(4, 2) NOT NULL,
                             consultation_id BIGINT NOT NULL,

                             CONSTRAINT uk_vital_signs_consultation
                                 UNIQUE (consultation_id),

                             CONSTRAINT fk_vital_signs_consultation
                                 FOREIGN KEY (consultation_id) REFERENCES consultations (id)
);

CREATE INDEX idx_consultations_patient_date
    ON consultations (patient_id, consultation_date_time DESC);

CREATE INDEX idx_consultations_doctor
    ON consultations (doctor_id);

CREATE INDEX idx_allergys_patient
    ON allergys (patient_id);

CREATE INDEX idx_continuous_medications_patient
    ON continuous_medications (patient_id);

CREATE INDEX idx_surgeries_patient_date
    ON surgeries (patient_id, surgery_name DESC);